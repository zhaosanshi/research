#!/usr/bin/env python3
"""compare_xmodel.py -- cross-model block, Chinese pilot (RESULTS.md §8) vs English materials, cell by cell.

  python compare_xmodel.py              # X20k probes: P(user) per model x cell, forced-'user' fake-turn counts
  python compare_xmodel.py --ownvoice   # same for the own-voice meta probes (filler generated by the model itself)
  python compare_xmodel.py --e2e        # temperature-1 sampling cells (first-token draws, continuations, full answers)

P(user) columns: 'user' = the lowercase role word only (the pilot's definition; pilot values are rounded to 1e-6, so a
pilot 0 means < 5e-7); 'family' = user/User/USER/Human/用户 summed from the unrounded p_role_exact field (English runs
only); 'role' = every role word incl. assistant/AI (upper bound).  Fake-turn detection as in compare_zh_en.is_fake.
"""
import argparse
import json
import math
import os
import statistics
from collections import defaultdict

import re

from compare_zh_en import is_fake

# e2e_sample.py flags any text containing <USER_REQUEST>, which also catches prose such as "there is no actual request in
# the `<USER_REQUEST>` block".  For sampled text require the tag at the start of a line, the metadata line, or a role line.
STRICT_WRAP = re.compile(r"(?m)^[ \t]*</?USER_REQUEST>|<ADDITIONAL_METADATA>|The current local time is")
STRICT_ROLE = re.compile(r"(?m)^(?:user|User|USER|human|Human|用户)[ \t]*[:：]?[ \t]*\n\S")


def is_fake_strict(text: str) -> bool:
    return bool(STRICT_WRAP.search(text) or STRICT_ROLE.search(text))


R = "results"
MODELS = ["Llama-3.1-8B-Instruct", "Llama-3.3-70B-Instruct", "Qwen3-4B", "Qwen3-8B", "Qwen3-14B", "Qwen3-32B",
          "gemma-3-4b-it", "gemma-3-12b-it", "gemma-3-27b-it"]
CELLS = ["X20k_c00", "X20k_c10", "X20k_c13", "X20k_m00", "X20k_m10", "X20k_m13"]
OWN_CELLS = ["X20k_m00", "X20k_m10", "X20k_m13"]
E2E_CELLS = ["m13", "m10", "c13"]
USER_WORDS = {"user", "human", "用户"}


def probe_files(m, ownvoice):
    if ownvoice:
        return f"{R}/xmodel_ownvoice_{m}.jsonl", f"{R}/en_xmodel_ownvoice_{m}.jsonl"
    en = f"{R}/en_cross_{m}.jsonl" if m == "Llama-3.1-8B-Instruct" else f"{R}/en_xmodel_{m}.jsonl"
    return f"{R}/xmodel_v1_{m}.jsonl", en


def load(path):
    cells = defaultdict(dict)
    if not os.path.exists(path):
        return cells
    for line in open(path, encoding="utf-8"):
        if line.strip():
            r = json.loads(line)
            if r.get("measure") == "slot_start":
                cells[r["condition"]][r.get("filler_seed", 0)] = r
    return cells


def p_user(r):
    return dict(r.get("top_role") or []).get("user", 0.0) or 0.0


def p_family(r):
    ex = r.get("p_role_exact")
    src = ex.items() if ex else (r.get("top_role") or [])
    return sum(v for k, v in src if k.strip().lower() in USER_WORDS)


def gm(vals):
    """geometric mean; all-zero -> '0'; zeros among positives are floored one decade under the smallest positive."""
    pos = [v for v in vals if v > 0]
    if not pos:
        return "0"
    floor = min(pos) / 10
    g = math.exp(sum(math.log(max(v, floor)) for v in vals) / len(vals))
    return f"{g:.1e}" + ("~" if len(pos) < len(vals) else "")


def fakes(recs):
    ff = [(r.get("force_first") or {}).get("user") or "" for r in recs]
    return f"{sum(1 for t in ff if is_fake(t))}/{len(ff)}"


def probe_tables(ownvoice):
    cells = OWN_CELLS if ownvoice else CELLS
    print(f"{'model':24s} {'cell':9s} | {'ZH user':>8s} {'ZH max':>8s} fake  | {'EN user':>8s} {'EN famil':>8s} {'EN role':>8s} {'EN max':>8s} fake  | n_zh n_en")
    for m in MODELS:
        zf, ef = probe_files(m, ownvoice)
        zh, en = load(zf), load(ef)
        if not zh and not en:
            continue
        for c in cells:
            rz, re_ = list(zh.get(c, {}).values()), list(en.get(c, {}).values())
            if not rz and not re_:
                continue
            zu = [p_user(r) for r in rz]
            eu = [p_user(r) for r in re_]
            ef_ = [p_family(r) for r in re_]
            er = [r.get("p_role") or 0 for r in re_]
            print(f"{m:24s} {c:9s} | {gm(zu):>8s} {max(zu) if zu else 0:8.1e} {fakes(rz) if rz else '-':5s} | "
                  f"{gm(eu):>8s} {gm(ef_):>8s} {gm(er):>8s} {max(ef_) if ef_ else 0:8.1e} {fakes(re_) if re_ else '-':5s} | {len(rz):4d} {len(re_):4d}")
        print()
    print("ZH values are rounded to 1e-6 by the pilot output (0 = below 5e-7); '~' = some seeds were 0 and were floored.")
    # a few English forced-'user' continuations per model so their shape can be eyeballed
    print("\nEnglish forced-'user' continuations (contaminated general cell, first two seeds):")
    for m in MODELS:
        en = load(probe_files(m, ownvoice)[1])
        for s, r in sorted(en.get("X20k_m13", {}).items())[:2]:
            print(f"  {m} seed {s}: {((r.get('force_first') or {}).get('user') or '')[:220]!r}")


def load_e2e(path):
    recs = []
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            if line.strip():
                r = json.loads(line)
                if "cell" in r:
                    recs.append(r)
    return recs


def e2e_line(tag, recs):
    n_first = sum(r["n_first"] for r in recs)
    user_hits = sum(v["n"] for r in recs for k, v in r["first_hits"].items() if k.strip().lower() == "user")
    any_hits = sum(r["first_hits_total"] for r in recs)
    conts = [h for r in recs for h in r["hit_continuations"]]
    fake_conts = sum(1 for h in conts if is_fake_strict(h["text"]))
    flag_conts = sum(1 for h in conts if h["fake_turn"])
    fulls = [s for r in recs for s in r["full_samples"]]
    full_fake = sum(1 for s in fulls if is_fake_strict(s["text"]))
    flag_full = sum(r["full_fake"] for r in recs)
    pu = gm([r["p_user"] for r in recs])
    ctx = int(statistics.mean(r["n_ctx_tokens"] for r in recs))
    note = "" if (fake_conts, full_fake) == (flag_conts, flag_full) else f"  [e2e_sample's own flags: {flag_conts}, {flag_full}]"
    print(f"  {tag:3s} seeds={len(recs)} ctx~{ctx:6d} P(user)={pu:>8s} | first draws: 'user' {user_hits}/{n_first}, any watched {any_hits}/{n_first} "
          f"| hit continuations fake {fake_conts}/{len(conts)} | full answers fake {full_fake}/{len(fulls)}{note}")
    shown = 0
    for h in conts + fulls:
        if is_fake_strict(h["text"]) and shown < 2:
            print(f"      example: {h['text'][:260]!r}")
            shown += 1


def e2e_tables():
    for m in MODELS:
        for cell in E2E_CELLS:
            if m == "Llama-3.1-8B-Instruct":
                zf, ef = None, f"{R}/en_e2e_{cell}.jsonl"
            else:
                zf, ef = f"{R}/e2e_x_{m}_{cell}.jsonl", f"{R}/en_e2e_x_{m}_{cell}.jsonl"
            zh = load_e2e(zf) if zf else []
            en = load_e2e(ef)
            if not zh and not en:
                continue
            print(f"{m} {cell}")
            if zh:
                e2e_line("ZH", zh)
            if en:
                e2e_line("EN", en)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ownvoice", action="store_true")
    ap.add_argument("--e2e", action="store_true")
    args = ap.parse_args()
    if args.e2e:
        e2e_tables()
    else:
        probe_tables(args.ownvoice)


if __name__ == "__main__":
    main()
