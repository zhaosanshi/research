"""
turn_boundary_probe.py  --  what does a chat model "want" to emit at the turn boundary?   (v3)

Project: Phantom_User pilot (2026-10-21).  Phenomenon: models spontaneously generate a fake *user*
turn (reported for Claude Code, Gemini CLI, OpenAI Codex and Cursor), then act on it next turn.

Hypothesis under test
---------------------
Spontaneous user-turn generation is the pretraining "speaker switch" prior leaking through a
one-token-thin post-training suppression: instruct training loss-masks user tokens (Ye et al.
2026, fn.13) and only teaches "emit EOT here".  Anything that dilutes P(EOT) at the boundary
lets the prior through.  Candidate diluters (one variable per condition):
  A2*  thin/no human input: last input is a tool result, not human text       (claude-code #57928)
  A1   text-form user template in context (<USER_REQUEST>...)                  (the original screenshot)
  A3*  self-contamination: earlier assistant turns already contain fake turns  (recurrence)
  A4   persona / metacognitive content instead of coding                       (Assistant Axis)
  A5*/L* context length (short builtin filler / model-generated long filler)   (Wang et al. 2025)
  A6   sign-off phrasing at the end of the answer                              (the original screenshot)
  B    base model with plain-text labels: what does the un-suppressed prior look like?

v2 result (Llama-3.1-8B-Instruct, <=3.5k ctx): no fake user turn in any condition; P(EOT)
eroded by meta content / length / sign-off, but the leaked mass went to "continue my own
answer", not to a speaker switch.  Hence v3 adds real long contexts (L* conditions, filler
generated by the model itself with make_filler.py) and fixes vocab classification
(<|eom_id|>/<|python_tag|> are tool-call structure, not role markers).

Two measurement points
----------------------
  answer_end : after the (model-generated, fixed) final answer, where EOT should come.
  slot_start : at the start of the assistant slot (right after the generation prompt).

Metrics (next-token distribution at the measured position)
----------------------------------------------------------
  p_eot      P(end-of-turn token of the chat template)
  p_header   P(role-header special token <|start_header_id|>)  = structural speaker switch
  p_eom      P(<|eom_id|>) end-of-message (tool-call) token, Llama 3.1 only
  p_role     P(text tokens that are exactly user/User/USER/human/Human/assistant/用户)
  p_ws       P(whitespace-only tokens)
  p_lt       P(text tokens starting with "<")
  top10, top_role, forced (EOT banned, greedy), unforced (normal stopping), unforced_stopped
"""
