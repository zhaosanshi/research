def detect_special(tokenizer):
    cands = [("<|eot_id|>", "<|start_header_id|>", "<|eom_id|>"),
             ("<|im_end|>", "<|im_start|>", None),
             ("<end_of_turn>", "<start_of_turn>", None),
             ("<|end|>", "<|user|>", None)]
    unk = tokenizer.unk_token_id

    def tid(t):
        if t is None:
            return None
        i = tokenizer.convert_tokens_to_ids(t)
        return None if (i is None or i == unk or i < 0) else i

    for eot, hdr, eom in cands:
        eid = tid(eot)
        if eid is not None:
            return eot, eid, hdr, tid(hdr), tid(eom)
    return tokenizer.eos_token, tokenizer.eos_token_id, None, None, None


def render_chat(messages, tokenizer, measure: str, eot_str: str) -> str:
    if measure == "slot_start":
        return tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True, **CHAT_KWARGS)
    text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=False, **CHAT_KWARGS)
    idx = text.rfind(eot_str)
    if idx < 0:
        raise RuntimeError("end-of-turn string not found in rendered template; check detect_special()")
    return text[:idx]


def render_base(messages, measure: str, label_user="User:", label_asst="Assistant:", label_tool="Tool:") -> str:
    parts = []
    for m in messages:
        if m["role"] == "system":
            parts.append(m["content"])
        elif m["role"] == "user":
            parts.append(f"{label_user} {m['content']}")
        elif m["role"] == "assistant":
            parts.append(f"{label_asst} {m['content']}")
        else:
            parts.append(f"{label_tool} {m['content']}")
    text = "\n\n".join(parts)
    if measure == "slot_start":
        text += f"\n\n{label_asst}"
    return text


