def build_conv(kind: str = "coding", n_turns: int = 5, wrapper: bool = False,
               contam_k: int = 0, end_style: str = "neutral", thin_input: bool = False,
               tool_role: str = "user", pre_tool_signoff: bool = False,
               filler: Optional[List[Tuple[str, str]]] = None,
               final_answer: Optional[str] = None, target_tokens: int = 0,
               pre_tool_style: str = "signoff", n_tool_steps: int = 0,
               thin_text: Optional[str] = None,
               prior_tool_text: Optional[str] = None,
               sys_extra: Optional[str] = None, asst_quote: Optional[str] = None,
               asst_quote_k: int = 1, approval_k: int = 0,
               user_paste: Optional[str] = None) -> Tuple[List[Dict[str, str]], str]:
    """Return (messages, measure_point).  n_turns pairs of (user, assistant) history, then either a
    thin-input tail (slot_start) or a final human turn + fixed final answer (answer_end).
    pre_tool_style: what the assistant said right before the machine input ('signoff' | 'question').
    n_tool_steps:   extra autonomous (tool result -> assistant) rounds inserted before the final input.
    thin_text:      final machine input text; None = TOOL_RESULT_BLOCK, '' = empty turn, or e.g. NOTIFICATION_TEXT."""
    pairs = filler if filler else (CODING_PAIRS if kind == "coding" else META_PAIRS)
    msgs: List[Dict[str, str]] = [{"role": "system", "content": SYSTEM_MSG[kind] + (sys_extra or "")}]
    turns: List[Tuple[str, str]] = []
    for i in range(n_turns):
        u, a = pairs[i % len(pairs)]
        if i >= len(pairs):          # mild variation to avoid exact repetition
            u = u + PHRASES["nth"].format(n=i + 1)
        turns.append((u, a))
    for i, (u, a) in enumerate(turns):
        if contam_k and i >= len(turns) - contam_k:
            a = a + FAKE_USER_TURN_TEXT
        if asst_quote and i >= len(turns) - asst_quote_k:
            a = a + asst_quote
        msgs.append({"role": "user", "content": wrap_user(u, i) if wrapper else u})
        msgs.append({"role": "assistant", "content": a})
    for r in range(approval_k):      # most recent history: repetitive propose/ask/approve/act rounds
        q, prop, ok, done = APPROVAL_ROUNDS[r % len(APPROVAL_ROUNDS)]
        fmt = dict(i=4 + r, sec=APPROVAL_SECTIONS[r % len(APPROVAL_SECTIONS)])
        j = n_turns + 2 * r
        msgs.append({"role": "user", "content": wrap_user(q.format(**fmt), j) if wrapper else q.format(**fmt)})
        msgs.append({"role": "assistant", "content": prop.format(**fmt)})
        msgs.append({"role": "user", "content": wrap_user(ok, j + 1) if wrapper else ok})
        msgs.append({"role": "assistant", "content": done.format(**fmt)})
    n_turns = n_turns + 2 * approval_k
    if thin_input:
        if prior_tool_text is not None:     # one earlier file read whose content carries role-formatted text
            u = PHRASES["read_log_user"]
            msgs.append({"role": "user", "content": wrap_user(u, n_turns) if wrapper else u})
            msgs.append({"role": "assistant", "content": PHRASES["read_log_asst"]})
            tr = prior_tool_text
            if tool_role == "user":
                msgs.append({"role": "user", "content": wrap_user(tr, n_turns) if wrapper else tr})
            else:
                msgs.append({"role": tool_role, "content": tr})
            msgs.append({"role": "assistant", "content": PHRASES["read_log_ack"]})
        if pre_tool_signoff:
            u = FINAL_USER_ASK if user_paste is None else FINAL_USER_ASK + "\n\n" + user_paste
            msgs.append({"role": "user", "content": wrap_user(u, n_turns) if wrapper else u})
            msgs.append({"role": "assistant", "content": PRE_TOOL_TEXT[pre_tool_style]})
        for s in range(n_tool_steps):
            tr = TOOL_STEP_RESULT.format(step=s + 1)
            if tool_role == "user":
                msgs.append({"role": "user", "content": wrap_user(tr, n_turns + 1 + s) if wrapper else tr})
            else:
                msgs.append({"role": tool_role, "content": tr})
            msgs.append({"role": "assistant", "content": TOOL_STEP_ASSISTANT.format(step=s + 1)})
        u = TOOL_RESULT_BLOCK if thin_text is None else thin_text
        idx = n_turns + 1 + n_tool_steps
        if tool_role == "user":
            msgs.append({"role": "user", "content": wrap_user(u, idx) if wrapper else u})
        else:
            msgs.append({"role": tool_role, "content": u})
        return msgs, "slot_start"
    if end_style == "ask":           # the answer hands the turn back with a question; measure right after '?'
        u = FINAL_USER_ASK
        msgs.append({"role": "user", "content": wrap_user(u, n_turns) if wrapper else u})
        msgs.append({"role": "assistant", "content": final_answer if final_answer is not None else ASK_ANSWER})
        return msgs, "answer_end"
    u = FINAL_USER[kind]
    msgs.append({"role": "user", "content": wrap_user(u, n_turns) if wrapper else u})
    if final_answer is not None:
        a = final_answer + ("\n\n" + SIGNOFF_SENTENCE if end_style == "signoff" else "")
    else:
        a = SIGNOFF_SENTENCE if end_style == "signoff" else NEUTRAL_END
    msgs.append({"role": "assistant", "content": a})
    return msgs, "answer_end"


