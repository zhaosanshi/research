_VOCAB_CACHE = {}


def classify_vocab(tokenizer, eot_id: int, header_id: Optional[int], eom_id: Optional[int]) -> Dict[str, List[int]]:
    key = (id(tokenizer), eot_id, header_id, eom_id)
    if key in _VOCAB_CACHE:
        return _VOCAB_CACHE[key]
    cats: Dict[str, List[int]] = {"eot": [eot_id], "header": [header_id] if header_id is not None else [],
                                  "eom": [eom_id] if eom_id is not None else [],
                                  "ws": [], "role": [], "lt": [], "special": [], "other": []}
    special = set(tokenizer.all_special_ids)
    fixed = {eot_id, header_id, eom_id}
    for i in range(len(tokenizer)):
        if i in fixed:
            continue
        if i in special:
            cats["special"].append(i)
            continue
        s = tokenizer.decode([i])
        if s == "":
            cats["other"].append(i)
        elif s.strip() == "":
            cats["ws"].append(i)
        elif s.strip().lower() in ROLE_WORDS:
            cats["role"].append(i)
        elif s.lstrip().startswith("<"):
            cats["lt"].append(i)
        else:
            cats["other"].append(i)
    _VOCAB_CACHE[key] = cats
    return cats


def disable_ngc_triton_bmm_override() -> bool:
    """NGC 26.06 torch (2.13 nightly) ships torch._native, which routes aten::bmm outer products -- the RoPE
    inv_freq x position_ids matmul -- to a Triton kernel.  Triton launches on the *current* CUDA device, so for
    weights living on any other device (device_map=auto, cuda:1) the kernel reads foreign memory: wrong RoPE,
    garbage generations at long context, flaky (sometimes 'Pointer argument cannot be accessed from Triton').
    Verified and fixed 2026-10-23 (verify_fix.py: 0/8 bad after disabling).  No-op outside that image."""
    try:
        import torch._native.registry as reg
    except Exception:
        return False
    try:
        reg.deregister_op_overrides(disable_dsl_names="triton")
        print("torch._native: triton op overrides disabled (NGC RoPE-on-wrong-device workaround)")
        return True
    except Exception as e:  # noqa: BLE001
        print(f"torch._native: could not disable triton overrides: {e}")
        return False


def load_model(path: str, dtype, device):
    """AutoModelForCausalLM, falling back to the image-text class for multimodal checkpoints (Gemma 3 -it)."""
    import os
    from transformers import AutoModelForCausalLM
    disable_ngc_triton_bmm_override()
    kw = dict(torch_dtype=dtype, device_map=device)
    if os.environ.get("ATTN_IMPL"):            # e.g. ATTN_IMPL=eager (Gemma 3 diagnostics); default = library choice
        kw["attn_implementation"] = os.environ["ATTN_IMPL"]
    try:
        return AutoModelForCausalLM.from_pretrained(path, **kw).eval()
    except (ValueError, KeyError, OSError) as e:
        from transformers import AutoModelForImageTextToText
        print(f"AutoModelForCausalLM failed ({type(e).__name__}: {str(e)[:120]}); trying AutoModelForImageTextToText")
        return AutoModelForImageTextToText.from_pretrained(path, **kw).eval()


def encode(tokenizer, text: str):
    enc = tokenizer(text, return_tensors="pt", add_special_tokens=False)
    bos = tokenizer.bos_token_id
    if bos is not None and enc.input_ids[0, 0].item() != bos:
        enc = tokenizer((tokenizer.bos_token or "") + text, return_tensors="pt", add_special_tokens=False)
    return enc


def generate_answer(model, tokenizer, messages, eot_id: int, base: bool, max_new: int,
                    label_user: str, label_asst: str):
    import torch
    if base:
        text = render_base(messages, "slot_start", label_user, label_asst)
    else:
        text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True, **CHAT_KWARGS)
    ids = encode(tokenizer, text).input_ids.to(next(model.parameters()).device)
    with torch.no_grad():
        gen = model.generate(ids, attention_mask=torch.ones_like(ids), max_new_tokens=max_new, do_sample=False,
                             eos_token_id=[eot_id, tokenizer.eos_token_id], pad_token_id=tokenizer.eos_token_id)
    new = gen[0, ids.shape[1]:]
    stopped = bool(len(new) and int(new[-1]) in (eot_id, tokenizer.eos_token_id))
    ans = tokenizer.decode(new, skip_special_tokens=True).strip()
    if base:
        for marker in (f"\n\n{label_user}", f"\n{label_user}", f"\n\n{label_asst}"):
            j = ans.find(marker)
            if j >= 0:
                ans = ans[:j].rstrip()
    return ans, stopped


def measure(model, tokenizer, text: str, eot_id: int, header_id: Optional[int], eom_id: Optional[int],
            max_forced: int) -> dict:
    import torch
    from transformers import LogitsProcessor, LogitsProcessorList
    device = next(model.parameters()).device
    ids = encode(tokenizer, text).input_ids.to(device)
    mask = torch.ones_like(ids)
    with torch.no_grad():
        try:   # only materialize the last position's logits (100k ctx x 128k vocab would be ~26GB)
            logits = model(ids, attention_mask=mask, logits_to_keep=1).logits[0, -1].float()
        except TypeError:
            logits = model(ids, attention_mask=mask).logits[0, -1].float()
    probs = torch.softmax(logits, dim=-1)
    cats = classify_vocab(tokenizer, eot_id, header_id, eom_id)
    rec = {"n_ctx_tokens": int(ids.shape[1])}
    for c in ("eot", "header", "eom", "ws", "role", "lt", "special", "other"):
        rec["p_" + c] = float(probs[cats[c]].sum()) if cats[c] else None
    top = torch.topk(probs, 10)
    rec["top10"] = [(tokenizer.decode([int(i)]), round(float(p), 5)) for p, i in zip(top.values, top.indices)]
    if cats["role"]:
        rp = probs[cats["role"]]
        rt = torch.topk(rp, min(5, len(cats["role"])))
        rec["top_role"] = [(tokenizer.decode([cats["role"][int(j)]]), round(float(p), 6)) for p, j in zip(rt.values, rt.indices)]
        # unrounded per-word probabilities (top_role rounds to 1e-6, too coarse for the English clean cells / Qwen / Gemma)
        rec["p_role_exact"] = {tokenizer.decode([cats["role"][int(j)]]): float(p) for p, j in zip(rt.values, rt.indices)}
    if CONTAM_ROLE_WORD != "user":   # probability of the contaminant's role word (its first token) at the slot
        ids_w = tokenizer.encode(CONTAM_ROLE_WORD, add_special_tokens=False)
        if ids_w:
            rec["p_contam_word"] = {"word": CONTAM_ROLE_WORD, "first_token": tokenizer.decode(ids_w[:1]),
                                    "n_tokens": len(ids_w), "p": float(probs[ids_w[0]])}

    class Ban(LogitsProcessor):
        def __init__(self, banned):
            self.banned = [b for b in banned if b is not None]

        def __call__(self, input_ids, scores):
            for b in self.banned:
                scores[:, b] = float("-inf")
            return scores

    with torch.no_grad():
        gen = model.generate(ids, attention_mask=mask, max_new_tokens=max_forced, do_sample=False,
                             logits_processor=LogitsProcessorList([Ban([eot_id, tokenizer.eos_token_id])]),
                             pad_token_id=tokenizer.eos_token_id)
    rec["forced"] = tokenizer.decode(gen[0, ids.shape[1]:], skip_special_tokens=False)
    with torch.no_grad():
        gen2 = model.generate(ids, attention_mask=mask, max_new_tokens=max_forced, do_sample=False,
                              eos_token_id=[eot_id, tokenizer.eos_token_id], pad_token_id=tokenizer.eos_token_id)
    new = gen2[0, ids.shape[1]:]
    rec["unforced"] = tokenizer.decode(new, skip_special_tokens=False)
    rec["unforced_stopped"] = bool(len(new) and int(new[-1]) in (eot_id, tokenizer.eos_token_id))
    rec["rendered_tail"] = text[-240:]
    return rec


def force_first_continuations(model, tokenizer, text: str, token_strs: List[str], n_new: int) -> Dict[str, Optional[str]]:
    """Teacher-force a candidate first token at the measured position and continue greedily.
    Disambiguates 'user' as a role label ('user\\n<USER_REQUEST>...') from 'user' as a sentence start ('用户提供了...')."""
    import torch
    device = next(model.parameters()).device
    base_ids = encode(tokenizer, text).input_ids.to(device)
    out: Dict[str, Optional[str]] = {}
    for s in token_strs:
        tid = tokenizer.convert_tokens_to_ids(s)
        if tid is None or tid < 0 or tid == tokenizer.unk_token_id:
            enc = tokenizer.encode(s, add_special_tokens=False)
            tid = enc[0] if enc else None
        if tid is None:
            out[s] = None
            continue
        ids = torch.cat([base_ids, torch.tensor([[tid]], device=device)], dim=1)
        with torch.no_grad():
            gen = model.generate(ids, attention_mask=torch.ones_like(ids), max_new_tokens=n_new, do_sample=False,
                                 pad_token_id=tokenizer.eos_token_id)
        out[s] = tokenizer.decode(gen[0, base_ids.shape[1]:], skip_special_tokens=False)
    return out


def load_filler(path: Optional[str]):
    if not path:
        return None, None
    pairs, toks = [], []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                d = json.loads(line)
                pairs.append((d["user"], d["assistant"]))
                toks.append(int(d.get("n_tokens", 0)))
    return pairs, toks


def fit_n_turns(toks: List[int], target: int, overhead_per_turn: int = 14) -> int:
    """Number of filler pairs whose content tokens (+template overhead) reach the target."""
    total, n = 0, 0
    for t in toks:
        if total >= target:
            break
        total += t + overhead_per_turn
        n += 1
    return max(1, n)


