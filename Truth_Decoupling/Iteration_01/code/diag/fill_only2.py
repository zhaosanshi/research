def te_cells(model, i, qs, need_judged=True):
    """{q: (value, answered, text)} of TE on split i; and the cells of its baseline_conf_E2 against T2."""
    split = ("tune", "test")[i]
    _, el, _, _, sdot = setting(model)
    D, run = run_of(model, i)
    w = MP.work(run, split, "fillctl")
    tx = MP.fr.raw_texts(w)
    want = "E_L%d_conf_E2-" % el
    conds = sorted({c for (_, c) in tx if c.startswith(want)})
    if len(conds) != 1:
        raise SystemExit("%s %s: TE conditions in %s: %s" % (model, split, w, conds))
    c = conds[0]
    if not need_judged:
        return {q: (None, None, tx[(q, c)]) for q in qs if (q, c) in tx}, c
    st, bl = ps.load(w, "pro")
    miss = [q for q in qs if st.get((q, c), "?") == "?"]
    if miss:
        raise SystemExit("%s %s: %d questions without a TE verdict" % (model, split, len(miss)))
    st1, bl1 = ps.load(D.m["d"][i], "pro")
    same = sum(st.get((q, "baseline_conf_E2")) == st1.get((q, "baseline_conf_E2")) and
               bl.get((q, "baseline_conf_E2")) == bl1.get((q, "baseline_conf_E2")) for q in qs)
    return {q: (V[st[(q, c)]], not bl[(q, c)], tx[(q, c)]) for q in qs}, (c, same)


def c25_cells(model, i, qs):
    """{q: (value, answered, text)} of the arm x_E2:E<L>.w.p<s_sel>+C<CL>.w.m0.25 (forced_e_fill.first_rung)."""
    sc = N2.choice(model)["strength"]
    sp, text = N.build(model, i, "x_E2", sc, N.restricted(model, i))
    arm = sp.cEC(sc, "0-25")
    return {q: (V[sp.st[(q, arm)]], not sp.blank[(q, arm)], text.ec[(q, arm)]) for q in qs}


def load(need_judged=True):
    T = FO.load_tq()
    ok = FO.check_tq(T)
    X = {}
    for i, name in SPLITS:
        X[name] = {}
        for m in ORDER:
            qs, P = T[name][m]
            te, info = te_cells(m, i, qs, need_judged)
            c25 = c25_cells(m, i, qs)
            X[name][m] = (qs, P, te, c25, info)
    return T, X, ok


def systems(P, te, c25, q):
    """{name: (value, answered, text)} of the systems on question q."""
    d = P[q]
    s0, se, sn1 = d["S0"][:3], d["SE"][:3], d["SN1"][:3]
    inb = not d["S0"][1]
    out = {"S0": s0, "SE": se, "SN1": sn1, "TE": te[q], "conf": d["conf"][:3],
           "fill EC": FO.cell(d, "fill EC")[:3], "fill prompt": FO.cell(d, "fill prompt")[:3]}
    if not inb:
        for k in ("fill pE2", "fill pE1", "fill EC1", "fill EC1c"):
            out[k] = s0
        return out
    out["fill pE1"] = te[q]
    if se[1]:
        out["fill pE2"] = out["fill EC1"] = out["fill EC1c"] = se
    else:
        out["fill pE2"] = te[q]
        out["fill EC1"] = c25[q]
        out["fill EC1c"] = sn1 if d["SN1"][3] in ("0", "0.25") else se
    return out


