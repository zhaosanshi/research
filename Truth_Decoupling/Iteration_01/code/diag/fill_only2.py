def export():
    import numpy as np
    T, X, ok = load(need_judged=False)
    if not ok:
        raise SystemExit("fill_only checks MISMATCH")
    for m in ORDER:
        root = os.path.join(SP.OUT, m)
        if os.path.exists(os.path.join(root, "fo_items_items.json")):
            raise SystemExit("%s: fo_items already exported" % m)
        have = SKP.lookup(m)
        items, seen, tally = [], set(), {}

        def add(key, qt, c):
            if not c[1] or not c[2].strip():
                return
            h = SP.sha1(SP.statement(qt, c[2]))
            if h in have:
                tally[key + " have"] = tally.get(key + " have", 0) + 1
                return
            if h in seen:
                return
            seen.add(h)
            tally[key + " new"] = tally.get(key + " new", 0) + 1
            items.append(dict(id=h, split=key, question=qt, answer=c[2], answer_sha1=SP.sha1(c[2]), value=c[0], answered=True,
                              neg=bool(SP.NEG_RE.match(c[2]))))
        for i, name in SPLITS:
            qs, P, te, c25, _ = X[name][m]
            for q in qs:
                d = P[q]
                if d["S0"][1]:
                    continue
                for f in ("fill EC", "fill E", "fill C", "fill prompt", "fill N1"):
                    add("tqa %s %s" % (name, f), d["qt"], FO.cell(d, f))
                tc = te.get(q)
                if tc is not None:
                    add("tqa %s TE" % name, d["qt"], (None, True, tc[2]))
                if not d["SE"][1]:
                    add("tqa %s C0.25" % name, d["qt"], c25[q])
        for x in items:
            if SP.sha1(SP.statement(x["question"], x["answer"])) != x["id"]:
                raise SystemExit("statement of %s" % x["id"])
        if not items:
            print("%s: nothing to score" % m)
            continue
        SP.save_items(os.path.join(root, "fo_items_items.json"), dict(model=m, source="fo_items", items=items))
        k = min(16, len(items))
        pick = sorted(np.random.default_rng(20261122).choice(len(items), k, replace=False).tolist())
        chk = [items[j] for j in pick]
        perm = np.random.default_rng(20261123).permutation(k).tolist()
        for src, xs in (("fo_chk", chk), ("fo_chka", chk), ("fo_chkb", [chk[j] for j in perm])):
            SP.save_items(os.path.join(root, src + "_items.json"), dict(model=m, source=src, items=xs))
        print("%s: new statements %d | %s" % (m, len(items), " | ".join("%s %d" % kv for kv in sorted(tally.items()))))


def check_fo(model):
    """fo_chk twice in order and once shuffled must agree exactly (as selfjudge_stack_pick.check_b)."""
    maps = {}
    for s in ("fo_chk", "fo_chka", "fo_chkb"):
        if not os.path.exists(os.path.join(SP.OUT, model, s + "_probe.json")):
            return None
        _, meta, z = SP.read_probe(model, source=s)
        if meta.get("batch_size") != 1:
            raise SystemExit("%s: %s is not batch 1" % (model, s))
        maps[s] = {str(h): float(z["baseline__margin"][j]) for j, h in enumerate(z["statement_sha1"])}
    a, b, c = maps["fo_chk"], maps["fo_chka"], maps["fo_chkb"]
    if set(a) != set(b) or set(a) != set(c):
        raise SystemExit("%s: fo check sets differ" % model)
    return len(a), max(abs(a[h] - b[h]) for h in a), max(abs(a[h] - c[h]) for h in a)


