# ---- generation check -------------------------------------------------------------------------------------------- #
def gencheck(model, split, fte):
    _, el, cl, sdash, sdot = setting(model)
    i = {"tune": 0, "test": 1}[split]
    D, run = run_of(model, i)
    fse = "%s/eval_extra/gen/x_E2--E%d-w-p%s-at-prompt_%s.json" % (run, el, sdash, split)
    te, se = json.load(open(fte)), json.load(open(fse))
    bad = []
    if te.get("arm") != "conf_E2:E%d.w.p%s" % (el, sdot) or se.get("arm") != "x_E2:E%d.w.p%s" % (el, sdot):
        bad.append("arm")
    if te.get("base_prompt") != "conf_E2" or se.get("base_prompt") != "x_E2":
        bad.append("base_prompt")
    for k in SAME_TOP:
        if k in ("completed", "execution_complete") and te.get("partial"):
            continue
        if te.get(k) != se.get(k):
            bad.append(k)
    skip = ("arm", "base_prompt", "cohort_sha256", "partial")    # cohort hash follows the base prompt; partial = pilot
    gte = {k: v for k, v in te.get("generation_contract", {}).items() if k not in skip}
    gse = {k: v for k, v in se.get("generation_contract", {}).items() if k not in skip}
    gdiff = sorted(k for k in set(gte) | set(gse) if gte.get(k) != gse.get(k))
    diff_top = sorted(k for k in set(te) | set(se) if te.get(k) != se.get(k))
    n = len(te["rows"])
    if te["question_ids"] != se["question_ids"][:len(te["question_ids"])] or [r["pair_id"] for r in te["rows"]] != \
            [r["pair_id"] for r in se["rows"]][:n]:
        bad.append("question order")
    if not te.get("partial") and n != len(se["rows"]):
        bad.append("row count")
    wsame = sum(a["write"] == b["write"] for a, b in zip(te["rows"], se["rows"]))
    t2 = MP.fr.raw_texts(D.m["d"][i])
    bsame = sum(t2.get((r["pair_id"], "baseline_conf_E2")) == r["baseline_text"] for r in te["rows"])
    bmiss = sum((r["pair_id"], "baseline_conf_E2") not in t2 for r in te["rows"])
    if bsame + bmiss != n:
        bad.append("baseline_text vs T2")
    empty = sum(not r["text"].strip() for r in te["rows"])
    print("gencheck %s %s %s: %d rows (partial %s) | top-level keys that differ from SE: %s | generation contract keys that "
          "differ (besides arm, base_prompt, cohort_sha256, partial): %s | rows whose write record equals SE's %d (prefill diagnostics follow the prompt) | baseline_text = T2's text %d, "
          "T2 missing %d | empty %d, refusal rule %d, unfinished %d, mean tokens %.2f (SE %.2f) -> %s" % (
              model, split, os.path.basename(fte), n, te.get("partial"), diff_top, gdiff, wsame, bsame, bmiss, empty,
              sum(bool(r["refusal_rule"]) for r in te["rows"]), sum(not r["finished"] for r in te["rows"]),
              sum(r["n_tokens"] for r in te["rows"]) / n, sum(r["n_tokens"] for r in se["rows"][:n]) / n,
              "OK" if not bad and not gdiff else "FAILED %s" % bad))
    if bad or gdiff:
        raise SystemExit(1)


